import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';

const documentFile = 'dist/openapi.json';
const typesFile = 'packages/sdk/src/openapi.generated.ts';
const registryFile = 'packages/sdk/src/operations.generated.ts';
await mkdir('dist', { recursive: true });
execFileSync(process.execPath, ['apps/api/dist/export-openapi.js', documentFile], { stdio: 'inherit' });

const document = JSON.parse(await readFile(documentFile, 'utf8'));
const httpMethods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);
const operations = {};
for (const [path, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!httpMethods.has(method)) continue;
    const id = operation.operationId;
    if (!id || Object.hasOwn(operations, id)) throw new Error(`Invalid operation ID for ${method} ${path}`);
    const requestMedia = Object.keys(operation.requestBody?.content ?? {});
    if (
      requestMedia.length > 1 ||
      requestMedia.some((media) => !['application/json', 'multipart/form-data'].includes(media))
    ) {
      throw new Error(`Unsupported SDK request media for ${id}`);
    }
    const responseFormats = {};
    for (const [status, response] of Object.entries(operation.responses)) {
      if (!/^2\d\d$/.test(status)) continue;
      if (status === '204' || status === '205') {
        responseFormats[status] = 'empty';
        continue;
      }
      const content = Object.entries(response.content ?? {});
      if (content.length === 0 || content.some(([, media]) => !media.schema)) {
        throw new Error(`Missing success response schema for ${method} ${path} (${status})`);
      }
      const formats = new Set(
        content.map(([media, { schema }]) =>
          schema.format === 'binary' ? 'blob' : media.includes('json') ? 'json' : 'text',
        ),
      );
      if (formats.size !== 1) throw new Error(`Ambiguous SDK response format for ${id} (${status})`);
      responseFormats[status] = [...formats][0];
    }
    if (Object.keys(responseFormats).length === 0) throw new Error(`Missing SDK success response for ${id}`);
    operations[id] = {
      method: method.toUpperCase(),
      path,
      bearer: operation.security?.some((scheme) => 'bearer' in scheme) ?? false,
      multipart: requestMedia[0] === 'multipart/form-data',
      responseFormats,
    };
  }
}

async function emit(file, source) {
  const generated = await format(`// Generated by pnpm sdk:generate.\n\n${source}`, {
    ...(await resolveConfig(file)),
    filepath: file,
  });
  if (process.argv.includes('--check')) {
    if ((await readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== generated) {
      throw new Error(`${file} is out of date. Run pnpm sdk:generate and commit the result.`);
    }
  } else {
    await writeFile(file, generated);
  }
}

const ast = await openapiTS(document, { alphabetize: true, defaultNonNullable: false });
await emit(typesFile, astToString(ast));
await emit(registryFile, `export const restOperations = ${JSON.stringify(operations, null, 2)} as const;\n`);
